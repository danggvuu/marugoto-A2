def kanji_to_hv(word):
    """Compute Han-Viet pronunciation for a word."""
    # If katakana
    if re.search(r'[\u30A0-\u30FF]', word) and not re.search(r'[\u4E00-\u9FFF]', word):
        return "[Phiên âm]"
    # Extract kanji characters
    kanji_chars = [c for c in word if '\u4e00' <= c <= '\u9fff']
    if not kanji_chars:
        return ""
    hvs = [KANJI_TO_HV.get(c, "") for c in kanji_chars]
    hvs = [h for h in hvs if h]
    if hvs:
        return "[" + " ".join(hvs) + "]"
    return ""

