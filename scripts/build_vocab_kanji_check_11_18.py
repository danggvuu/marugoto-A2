#!/usr/bin/env python3
"""Build the scoped A2.1 lesson 11–18 vocabulary/Kanji practice dataset."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LESSONS = {f"A2-{number}" for number in range(11, 19)}

vocab_source = json.loads((ROOT / "data/master_vocab_enriched.json").read_text(encoding="utf-8"))
kanji_source = json.loads((ROOT / "data/kanji_vocab_11_18.json").read_text(encoding="utf-8"))
character_source = json.loads((ROOT / "data/kanji_extracted.json").read_text(encoding="utf-8"))
allowed_kanji = {item["char"] for item in character_source
                 if item.get("lesson") in {f"L{number}" for number in range(11, 19)}}
han = re.compile(r"[\u3400-\u9fff]")

vocab = []
seen = set()
for item in vocab_source:
    if item.get("l") not in LESSONS or not item.get("vi") or not item.get("kana") or han.search(item["kana"]):
        continue
    key = (item.get("l"), item.get("jp") or item.get("kanji"), item["kana"])
    if key in seen:
        continue
    seen.add(key)
    vocab.append({
        "id": f"vocab:{item['l']}:{item.get('jp') or item.get('kanji')}:{item['kana']}",
        "lesson": item["l"],
        "jp": item.get("jp") or item.get("kanji"),
        "kana": item["kana"],
        "vi": item["vi"],
        "romaji": item.get("romaji", ""),
    })

kanji = []
seen = set()
for item in kanji_source:
    lesson = int(item["lesson"])
    if lesson not in range(11, 19) or not item.get("kanji") or not item.get("kana"):
        continue
    characters = set(han.findall(item["kanji"]))
    if not characters or not characters.issubset(allowed_kanji) or han.search(item["kana"]):
        continue
    key = (lesson, item["kanji"], item["kana"])
    if key in seen:
        continue
    seen.add(key)
    kanji.append({
        "id": f"kanji:{lesson}:{item['kanji']}:{item['kana']}",
        "lesson": f"A2-{lesson}",
        "jp": item["kanji"],
        "kana": item["kana"],
        "vi": item.get("vi", ""),
        "group": item.get("group", ""),
    })

payload = {
    "version": 2,
    "scope": "A2-11..A2-18",
    "lessons": sorted(LESSONS, key=lambda x: int(x.split("-")[1])),
    "allowedKanji": sorted(allowed_kanji),
    "sources": ["data/master_vocab_enriched.json", "data/kanji_vocab_11_18.json", "data/kanji_extracted.json"],
    "vocab": vocab,
    "kanji": kanji,
}
assert len({item["id"] for item in vocab + kanji}) == len(vocab + kanji)
assert all(any(item["lesson"] == lesson for item in kanji) for lesson in LESSONS)
target = ROOT / "assets/data/vocab_kanji_check_11_18_data.js"
target.write_text(
    "/* Generated by scripts/build_vocab_kanji_check_11_18.py. Scope: A2-11..A2-18. */\n"
    "window.VOCAB_KANJI_CHECK_DATA = "
    + json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    + ";\n",
    encoding="utf-8",
)
print(f"Generated {len(vocab)} vocabulary and {len(kanji)} Kanji-vocabulary entries: {target}")
