    sources = [
        (ROOT / f"tests/On_Tap_Mini_Test_A2_{suffix}.html").read_text(encoding="utf-8")
        for suffix in ["11_14", "15_18"]
    ]
    # These arrays are intentionally not the broader PDF compound banks: every
    # displayed character in Kanji practice must come from L11–18.
    vocab = json.loads((ROOT / "data/master_vocab_enriched.json").read_text(encoding="utf-8"))
    vocab = [dict(item, jp=item["kana"], kanji=item["kana"])
             for item in vocab if item.get("l") in LESSONS]
    characters = json.loads((ROOT / "data/kanji_extracted.json").read_text(encoding="utf-8"))
    characters = [item for item in characters if item.get("lesson") in {f"L{n}" for n in range(11, 19)}]
    scoped = (ROOT / "assets/data/vocab_kanji_check_11_18_data.js").read_text(encoding="utf-8")
    compounds = json.loads(scoped.split(" = ", 1)[1].strip().removesuffix(";"))["kanji"]
    typing_kanji = [
        dict(item, id="review-" + item["id"], kanji=item["jp"],
             accepted=[item["kana"]], hv="", stt=i + 1,
             group="11-14" if int(item["lesson"][3:]) <= 14 else "15-18",
             note=f"{item['jp']} — {item['kana']} — {item['vi']}")
        for i, item in enumerate(compounds)
    ]
    sentences = [item for item in SENTENCE_TYPING_DATA if item.get("lesson") in LESSONS]
    payload = {
        "VOCAB_DATA": vocab, "KANJI_DATA": characters,
        "SENTENCE_TYPING_DATA": sentences,
        "KANJI_11_14_DATA": [item for item in typing_kanji if item["group"] == "11-14"],
        "KANJI_15_18_DATA": [item for item in typing_kanji if item["group"] == "15-18"],
    }
    (ROOT / "assets/data/review_11_18_data.js").write_text(
        "/* Generated by scripts/build_review_11_18.py. */\nwindow.REVIEW_11_18_DATA = "
        + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    theory = "".join(panel(source, "tab-theory") for source in sources)
    cheatsheet = "".join(panel(source, "tab-cheatsheet") for source in sources)
    typing = panel(sources[1], "tab-typing")
    typing = typing.replace("Từ Vựng A2 (135 từ)", f"Từ Vựng A2 ({len(vocab)} từ)")
    typing = typing.replace(
        "Luyện gõ theo bộ tài liệu cô gửi (<strong>PDF Tổng hợp ngữ pháp L11–L18</strong>, Kaiwa Mid 2 &amp; 2 file PDF Kanji 11–18).",
        "Luyện câu bài 11–18, từ vựng Kana và từ ghép chỉ chứa Kanji thuộc danh sách 11–18.")
