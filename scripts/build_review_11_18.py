from l15_18_typing_data import SENTENCE_TYPING_DATA

ROOT = Path(__file__).resolve().parents[1]
LESSONS = {f"A2-{n}" for n in range(11, 19)}


def panel(source, name):
    """Extract a complete nested div by ID without depending on indentation."""
    start = re.search(rf'<div\b[^>]*\bid="{re.escape(name)}"[^>]*>', source)
    if not start:
        raise ValueError(f"Missing panel {name}")
    depth = 1
    for tag in re.finditer(r"</?div\b[^>]*>", source[start.end():]):
        depth += -1 if tag[0].startswith("</") else 1
        if depth == 0:
            return source[start.end():start.end() + tag.start()]
    raise ValueError(f"Unclosed panel {name}")


